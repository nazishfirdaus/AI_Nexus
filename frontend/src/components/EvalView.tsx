import { useEffect, useState } from "react"
import { api, type EvalRun, type EvalRunSummary } from "../utils/api"
import { formatDate } from "../utils/documents"
import { Icon } from "./Icon"

interface Props {
  onError: (message: string) => void
}

type Cell = string | number | boolean | null | undefined

function display(value: unknown): string {
  if (value === null || value === undefined) return "—"
  if (typeof value === "number") {
    return Number.isInteger(value) ? String(value) : value.toFixed(3)
  }
  if (typeof value === "boolean") return value ? "yes" : "no"
  if (typeof value === "object") return JSON.stringify(value)
  return String(value)
}

/** Summary keys that read well as headline metrics. */
const HEADLINE = [
  "items",
  "recall_at_k",
  "mrr_at_k",
  "answer_accuracy",
  "citation_support_rate",
  "pii_leak_rate",
  "no_context_rate",
  "answered_rate",
  "median_e2e_s",
  "p95_e2e_s",
]

export function EvalView({ onError }: Props) {
  const [runs, setRuns] = useState<EvalRunSummary[]>([])
  const [selected, setSelected] = useState<string | null>(null)
  const [detail, setDetail] = useState<EvalRun | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    let cancelled = false
    api
      .evalRuns()
      .then((list) => {
        if (cancelled) return
        setRuns(list)
        if (list.length > 0) setSelected(list[0].name)
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          onError(err instanceof Error ? err.message : "Could not load eval runs.")
        }
      })
      .finally(() => {
        if (!cancelled) setLoading(false)
      })
    return () => {
      cancelled = true
    }
  }, [onError])

  useEffect(() => {
    if (!selected) {
      setDetail(null)
      return
    }
    let cancelled = false
    api
      .evalRun(selected)
      .then((run) => {
        if (!cancelled) setDetail(run)
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          onError(err instanceof Error ? err.message : "Could not load the run.")
        }
      })
    return () => {
      cancelled = true
    }
  }, [selected, onError])

  const summary = detail?.summary ?? {}
  const headline = HEADLINE.filter((key) => key in summary)
  const rowKeys =
    detail && detail.rows.length > 0
      ? Object.keys(detail.rows[0]).slice(0, 8)
      : []

  return (
    <section className="view view--eval is-active" aria-label="Evaluation">
      <div className="page">
        <div className="page-head">
          <div>
            <span className="eyebrow">Evaluation</span>
            <h2 className="display">Harness runs</h2>
            <p className="page-sub">
              Artifacts written by <span className="mono">evaluation/run_eval.py</span>.
              Read straight from disk; nothing here is generated by the UI.
            </p>
          </div>
        </div>

        {loading ? (
          <p className="source-empty">Loading runs…</p>
        ) : runs.length === 0 ? (
          <p className="source-empty">
            No <span className="mono">evaluation/results*.json</span> found.
          </p>
        ) : (
          <>
            <div className="stat-strip">
              {runs.slice(0, 4).map((run) => (
                <button
                  key={run.name}
                  type="button"
                  className={`stat stat--button${selected === run.name ? " is-active" : ""}`}
                  onClick={() => setSelected(run.name)}
                >
                  <span className="stat-label">{run.name}</span>
                  <span className="stat-value mono">{run.items}</span>
                  <span className="stat-foot">
                    {formatDate(run.modified_at)}
                  </span>
                </button>
              ))}
            </div>

            {detail && (
              <>
                <div className="card">
                  <div className="card-head">
                    <div>
                      <h3>{detail.name}</h3>
                      <p>
                        {detail.items} item{detail.items === 1 ? "" : "s"} · modified{" "}
                        {formatDate(detail.modified_at)}
                      </p>
                    </div>
                  </div>

                  {headline.length > 0 ? (
                    <div className="stat-strip stat-strip--flat">
                      {headline.map((key) => (
                        <div key={key} className="stat">
                          <span className="stat-label">{key}</span>
                          <span className="stat-value mono">
                            {display(summary[key])}
                          </span>
                        </div>
                      ))}
                    </div>
                  ) : (
                    <p className="source-empty">
                      This artifact has no <span className="mono">summary</span>{" "}
                      block; see the rows below.
                    </p>
                  )}
                </div>

                {detail.rows.length > 0 && (
                  <div className="table-shell">
                    <table className="doc-table">
                      <thead>
                        <tr>
                          <th scope="col" className="num">
                            #
                          </th>
                          {rowKeys.map((key) => (
                            <th key={key} scope="col">
                              {key}
                            </th>
                          ))}
                        </tr>
                      </thead>
                      <tbody>
                        {detail.rows.slice(0, 25).map((row, index) => (
                          <tr key={index}>
                            <td className="num">{index + 1}</td>
                            {rowKeys.map((key) => (
                              <td key={key} className="eval-cell">
                                {display(row[key])}
                              </td>
                            ))}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                    <div className="table-foot">
                      <span>
                        Showing {Math.min(25, detail.rows.length)} of{" "}
                        {detail.rows.length} rows
                      </span>
                      <span className="mono">{detail.name}</span>
                    </div>
                  </div>
                )}
              </>
            )}
          </>
        )}
      </div>

      <span className="sr-only">
        <Icon name="database" />
      </span>
    </section>
  )
}